# -*- coding: utf-8 -*-
"""Рис. 2. Карта уязвимостей горячего подключения памяти и роль языка Rust.

Сверху -- конвейер исполнения запроса (контроллер -> модель устройства QEMU
-> подсистема памяти гостя -> состояние памяти) с пятью горячими точками.
Снизу -- карточки точек: класс дефекта, пример CVE и оценка того, устраняет
ли дефект переход на язык с безопасной работой с памятью (Rust).
"""
import os
from diaglib import Fig, ACC_FILL, BOX_FILL

W, H = 170.0, 128.0
GREY = (238, 238, 238)


def build():
    f = Fig(W, H)
    # ---- конвейер ----
    py = 12.0
    ph = 15.0
    pw = 38.0
    gap = 5.0
    titles = ["Контроллер\n(хост)", "Модель устройства\nQEMU (C)",
              "Подсистема памяти\nгостя (ядро Linux, C)", "Состояние\nпамяти ВМ"]
    xs = []
    x = 3.0
    for i, t in enumerate(titles):
        xs.append(x)
        f.box(f"p{i}", x, py, pw, ph, t.split("\n"),
              fill=ACC_FILL if i in (1, 2) else BOX_FILL, pt=7.0)
        x += pw + gap
    for i in range(len(titles) - 1):
        x0 = xs[i] + pw
        f.link([(x0, py + ph / 2), (x0 + gap, py + ph / 2)],
               owners=(f"p{i}", f"p{i+1}"))

    # ---- горячие точки (бейджи) на конвейере, слева направо ----
    hot = [
        (xs[1] + pw / 2, "H1"),
        (xs[1] + pw + gap / 2, "H4"),
        (xs[2] + pw / 2 - 8, "H2"),
        (xs[2] + pw / 2 + 8, "H3"),
        (xs[3] + pw / 2, "H5"),
    ]
    for cx, name in hot:
        f.d.ellipse([f._xy(cx - 2.6, py + ph - 2.6), f._xy(cx + 2.6, py + ph + 2.6)],
                    fill=(60, 60, 60), outline=(0, 0, 0),
                    width=max(1, int(f.px(0.3))))
        f.text(cx, py + ph + 0.1, name, pt=6.4, bold=True, fill=(255, 255, 255))

    # ---- карточки ----
    cw, ch = 31.0, 60.0
    cy = 40.0
    cards = [
        ("H1. Модель устройства", ACC_FILL,
         ["Класс: use-after-free,",
          "выход за границу,",
          "разыменование NULL",
          "в коде устройства (C)",
          "",
          "для pc-dimm и virtio-mem",
          "в QEMU записей CVE",
          "в NVD не найдено"],
         "Rust: ДА — безопасная\nработа с памятью\nустраняет этот класс"),
        ("H4. Протокол: отказ", GREY,
         ["Семантика: молчаливый",
          "отказ извлечения,",
          "у QEMU нет тайм-аута;",
          "неперемещаемая",
          "страница блокирует",
          "изъятие навсегда",
          "",
          "Эксперимент 1"],
         "Rust: НЕТ — дефект\nпротокола, нужен\nконтроль на стороне\nконтроллера"),
        ("H2. Ядро: hot-remove", BOX_FILL,
         ["Класс: гонки и",
          "блокировки в пути",
          "изъятия памяти",
          "(core mm, C)",
          "",
          "CVE-2025-38681,",
          "CVE-2025-21931,",
          "CVE-2024-49934"],
         "Rust: ЧАСТИЧНО —\nлогика и конкуренция,\nне только память"),
        ("H3. Драйверы гостя", BOX_FILL,
         ["Класс: порядок",
          "операций, UAF при",
          "приостановке (C)",
          "",
          "CVE-2026-64244",
          "(путь virtio-mem),",
          "CVE-2026-74481,",
          "CVE-2026-90129"],
         "Rust: ЧАСТИЧНО —\nUAF устраняется,\nпорядок операций\nне гарантируется"),
        ("H5. Протокол: возврат", GREY,
         ["Семантика: сжатие",
          "best-effort; остаток",
          "при фрагментации;",
          "несговорчивый или",
          "бездрайверный гость",
          "не отдаёт память",
          "",
          "Эксперименты 2, 3"],
         "Rust: НЕТ — нужна\nпроверка факта и\nпредохранитель на\nхосте"),
    ]
    x = 2.5
    for i, (title, fill, body, verdict) in enumerate(cards):
        f.box(f"c{i}", x, cy, cw, ch, body, title=title, fill=fill,
              pt=6.5, title_pt=6.8)
        # вердикт Rust отдельной плашкой под карточкой
        f.box(f"r{i}", x, cy + ch + 1.5, cw, 15.0, verdict.split("\n"),
              fill=(250, 250, 250), pt=6.3)
        # связь точка -> карточка
        hx = hot[i][0]
        by = py + ph + 4.0 + 1.8 * i  # своя высота шины, линии не сливаются
        f.link([(hx, py + ph + 2.6), (hx, by), (x + cw / 2, by),
                (x + cw / 2, cy)], owners=(f"c{i}",), lw=0.25)
        x += cw + 2.5

    f.note(3.0, cy + ch + 17.5,
           "Вывод: Rust снимает ошибки памяти в модели устройства (H1) и частично "
           "в ядре (H2, H3),\nно не устраняет протокольные уязвимости (H4, H5). "
           "Уязвимости есть и у гипервизоров на Rust:\n"
           "Cloud Hypervisor CVE-2026-45782 (use-after-free), "
           "Firecracker CVE-2026-5747 (выход за границу).",
           pt=7.0)
    return f


if __name__ == "__main__":
    f = build()
    rep = f.report()
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "figures_out", "fig2_weakmap.tiff")
    f.save(out)
    print("saved", out)
    for k, v in rep.items():
        print(k, v if v else "ok")
