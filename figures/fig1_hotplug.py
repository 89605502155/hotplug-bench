# -*- coding: utf-8 -*-
"""Рис. 1. Общая схема горячего подключения оперативной памяти в KVM/QEMU.

Три дорожки (контроллер/хост, монитор QEMU, гостевое ядро) и два пути:
верхний ряд -- горячее подключение модуля DIMM через ACPI, нижний ряд --
паравиртуальное устройство virtio-mem. Схема показывает нормальный ход
расширения; ветви изъятия и точки отказа вынесены на рис. 2.
"""
import os
from diaglib import Fig, ACC_FILL, BOX_FILL

W, H = 170.0, 112.0


def build():
    f = Fig(W, H)
    # дорожки
    lane_y, lane_h = 9.0, 92.0
    xs = [3.0, 60.0, 117.0]
    lw = 50.0
    f.lane(xs[0], lane_y, lw, lane_h, "Контроллер / хост")
    f.lane(xs[1], lane_y, lw, lane_h, "Монитор QEMU")
    f.lane(xs[2], lane_y, lw, lane_h, "Гостевое ядро Linux")

    # ===== Верхний ряд: ACPI DIMM =====
    f.text(W / 2, 15.0, "Путь 1. Горячее подключение модуля DIMM через ACPI",
           pt=7.2, bold=True)
    y1 = 20.0
    bw, bh = 46.0, 17.0
    b1 = f.box("d1", 5.0, y1, bw, bh,
               ["Создать область памяти",
                "на хосте и виртуальный",
                "модуль; задать размер"],
               title="1. Запрос расширения", fill=ACC_FILL)
    b2 = f.box("d2", 62.0, y1, bw, bh,
               ["Подобрать слот и диапазон",
                "адресов в окне; включить",
                "область в адресное",
                "пространство гостя"],
               title="2. Отображение", fill=BOX_FILL)
    b3 = f.box("d3", 62.0, y1 + 19.0, bw, bh,
               ["Контроллер ACPI отмечает",
                "слот и возбуждает",
                "прерывание"],
               title="3. Событие ACPI", fill=BOX_FILL)
    b4 = f.box("d4", 119.0, y1, bw, bh,
               ["Интерпретатор ACPI,",
                "драйвер получает",
                "диапазон модуля"],
               title="4. Уведомление", fill=BOX_FILL)
    b5 = f.box("d5", 119.0, y1 + 19.0, bw, bh,
               ["Регистрация секций,",
                "перевод блоков (128 МиБ)",
                "в состояние online"],
               title="5. Онлайн", fill=ACC_FILL)
    dy = 21.0
    f.badge(5.0 + 1.6, y1 + 1.5, 1)
    f.badge(62.0 + 1.6, y1 + 1.5, 2)
    f.badge(62.0 + 1.6, y1 + dy + 1.5, 3)
    f.badge(119.0 + 1.6, y1 + 1.5, 4)
    f.badge(119.0 + 1.6, y1 + dy + 1.5, 5)
    # связи верхнего ряда (только между соседними дорожками)
    f.link([(51.0, y1 + bh / 2), (62.0, y1 + bh / 2)], owners=("d1", "d2"))
    f.link([(85.0, y1 + bh), (85.0, y1 + dy)], owners=("d2", "d3"))
    f.link([(108.0, y1 + dy + bh / 2), (119.0, y1 + dy + bh / 2)],
           owners=("d3", "d4"))
    f.link([(142.0, y1 + bh), (142.0, y1 + dy)], owners=("d4", "d5"))

    # ===== Нижний ряд: virtio-mem =====
    yy = 70.0
    f.text(W / 2, yy - 3.2,
           "Путь 2. Паравиртуальное устройство virtio-mem (блок 2 МиБ)",
           pt=7.2, bold=True)
    f.box("v1", 5.0, yy, bw, bh,
          ["Задать требуемый объём;",
           "опубликовать конфигурацию:",
           "блок, требуемый и",
           "подключённый объёмы"],
          title="A. Целевой объём", fill=ACC_FILL)
    f.box("v2", 62.0, yy, bw, bh,
          ["Проверить диапазон,",
           "сделать область доступной,",
           "подтвердить запрос",
           "драйвера"],
          title="C. Обработка запроса", fill=BOX_FILL)
    f.box("v3", 119.0, yy, bw, bh,
          ["Выбрать блоки, послать",
           "запрос подключения;",
           "регистрация памяти,",
           "перевод в online"],
          title="B/D. Драйвер гостя", fill=ACC_FILL)
    # virtio-mem: хост->QEMU->гость, и возврат запроса гость->QEMU
    f.link([(51.0, yy + bh / 2 - 3.0), (62.0, yy + bh / 2 - 3.0)],
           owners=("v1", "v2"))
    f.label(56.5, yy + bh / 2 - 4.4, "config")
    f.link([(108.0, yy + bh / 2 - 3.0), (119.0, yy + bh / 2 - 3.0)],
           owners=("v2", "v3"), head=True)
    f.label(113.5, yy + bh / 2 - 4.4, "уведомл.")
    f.link([(119.0, yy + bh / 2 + 4.0), (108.0, yy + bh / 2 + 4.0)],
           owners=("v2", "v3"))
    f.label(113.5, yy + bh / 2 + 2.6, "запрос")

    f.note(5.0, lane_y + lane_h + 1.6,
           "Общее: решение контроллера исполняет гость; шаг изменения ненулевой "
           "(128 МиБ для DIMM, 2 МиБ для virtio-mem),\n"
           "подтверждение приходит только по факту перевода памяти в online.",
           pt=6.0)
    return f


if __name__ == "__main__":
    f = build()
    rep = f.report()
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                       "figures_out", "fig1_hotplug.tiff")
    f.save(out)
    print("saved", out)
    for k, v in rep.items():
        print(k, v if v else "ok")
